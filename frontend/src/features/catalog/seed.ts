import { EXERCISE_ALTERNATIVES } from './data/alternatives';
import { EXERCISES } from './data/exercises';
import { ROUTINE_TEMPLATES } from './data/templates';

type SqlLiteral = string;

const text = (value: string): SqlLiteral => `'${value.replaceAll("'", "''")}'`;
const uuid = (value: string): SqlLiteral => `${text(value)}::uuid`;
const textArray = (values: readonly string[]): SqlLiteral =>
  values.length === 0 ? `'{}'::text[]` : `array[${values.map(text).join(', ')}]::text[]`;

/** The conditional update leaves `updated_at` alone when a row hasn't changed. */
function upsert(
  table: string,
  keys: readonly string[],
  columns: readonly string[],
  rows: readonly (readonly SqlLiteral[])[],
): string {
  const values = rows.map((row) => `  (${row.join(', ')})`).join(',\n');
  const assignments = columns.map((column) => `  ${column} = excluded.${column}`).join(',\n');
  const current = columns.map((column) => `${table}.${column}`).join(', ');
  const incoming = columns.map((column) => `excluded.${column}`).join(', ');

  return [
    `insert into ${table} (${[...keys, ...columns].join(', ')}) values`,
    values,
    `on conflict (${keys.join(', ')}) do update set`,
    assignments,
    `where (${current}) is distinct from (${incoming});`,
  ].join('\n');
}

function deleteRowsNotIn(
  table: string,
  keys: readonly string[],
  rows: readonly (readonly SqlLiteral[])[],
): string {
  const values = rows.map((row) => `  (${row.join(', ')})`).join(',\n');
  return `delete from ${table}\nwhere (${keys.join(', ')}) not in (values\n${values}\n);`;
}

function templateExerciseRows(): SqlLiteral[][] {
  return ROUTINE_TEMPLATES.flatMap((template) =>
    template.exercises.map((planned, position) => {
      const exercise = EXERCISES.find((candidate) => candidate.slug === planned.exerciseSlug);
      if (!exercise) throw new Error(`Unknown exercise in template: ${planned.exerciseSlug}`);

      return [
        uuid(template.id),
        String(position),
        uuid(exercise.id),
        String(planned.targetSets),
        String(planned.targetReps),
        String(planned.restSeconds),
      ];
    }),
  );
}

/**
 * Renders `supabase/seed.sql`. Every statement is safe to re-run, and only the
 * public catalog tables are touched, so seeding can't affect user data.
 * Exercises are never deleted because routines and history reference them.
 */
export function renderCatalogSeed(): string {
  const alternativeKeys = ['source_exercise_id', 'target_exercise_id', 'kind'];
  const alternativeKeyRows = EXERCISE_ALTERNATIVES.map((alternative) => [
    uuid(alternative.sourceExerciseId),
    uuid(alternative.targetExerciseId),
    text(alternative.kind),
  ]);
  const templateExerciseKeys = ['template_id', 'position'];
  const templateRows = templateExerciseRows();

  return [
    '-- Generated by scripts/generate-catalog-seed.ts. Do not edit by hand.',
    '-- Safe to run repeatedly. Touches public catalog tables only.',
    upsert(
      'public.exercises',
      ['id'],
      [
        'slug',
        'name',
        'pattern',
        'primary_muscles',
        'secondary_muscles',
        'equipment',
        'load_convention',
        'difficulty',
        'summary',
        'instructions',
        'cues',
        'mistakes',
        'asset_path',
        'motion_asset_path',
        'asset_alt',
      ],
      EXERCISES.map((exercise) => [
        uuid(exercise.id),
        text(exercise.slug),
        text(exercise.name),
        text(exercise.pattern),
        textArray(exercise.primaryMuscles),
        textArray(exercise.secondaryMuscles),
        text(exercise.equipment),
        text(exercise.loadConvention),
        String(exercise.difficulty),
        text(exercise.summary),
        textArray(exercise.instructions),
        textArray(exercise.cues),
        textArray(exercise.mistakes),
        text(exercise.assetPath),
        text(exercise.motionAssetPath),
        text(exercise.assetAlt),
      ]),
    ),
    deleteRowsNotIn('public.exercise_alternatives', alternativeKeys, alternativeKeyRows),
    upsert(
      'public.exercise_alternatives',
      alternativeKeys,
      ['rationale', 'position'],
      EXERCISE_ALTERNATIVES.map((alternative, index) => [
        ...(alternativeKeyRows[index] as SqlLiteral[]),
        text(alternative.rationale),
        String(alternative.position),
      ]),
    ),
    upsert(
      'public.routine_templates',
      ['id'],
      ['slug', 'title', 'description', 'position'],
      ROUTINE_TEMPLATES.map((template, position) => [
        uuid(template.id),
        text(template.slug),
        text(template.title),
        text(template.description),
        String(position),
      ]),
    ),
    deleteRowsNotIn(
      'public.routine_template_exercises',
      templateExerciseKeys,
      templateRows.map((row) => row.slice(0, 2)),
    ),
    upsert(
      'public.routine_template_exercises',
      templateExerciseKeys,
      ['exercise_id', 'target_sets', 'target_reps', 'rest_seconds'],
      templateRows,
    ),
  ].join('\n\n')
    .concat('\n');
}
